package main

// resources.go says of its column list: "columns declares headers and cell
// extractors in CRD-declared order." That was a comment, and a comment cannot
// fail. It stopped being true when FleetAction's CRD gained the `Verb`
// (.spec.customType) and `Outcome` (.status.outcomeCertainty) printer columns and
// this registry did not: the two operator surfaces that a closed verb enum and a
// fail-closed unestablished outcome BOTH rest on existed in `kubectl get` and not
// in `swarmctl get`, while the spec recorded the surface as implemented.
//
// So this derives the expectation instead of restating it. The CRD's
// additionalPrinterColumns are generated by controller-gen from the
// +kubebuilder:printcolumn markers in api/v1 and are what the API server serves;
// reading them here means the next column added to FleetAction cannot reach
// kubectl and miss swarmctl without something going red. Nothing is transcribed,
// so nothing here needs editing when a column is added — only resources.go does,
// which is the point.
//
// SCOPE, AND WHY IT IS NOT EVERY KIND. Three other registered kinds diverge from
// their CRD columns: Robot omits `Action`, and ModelRollout and ModelPolicy both
// omit `Target`. Each is a real gap and none is this change's to move — moving a neighbour's operator
// surface is how two changes land conflicting tables. This test covers FleetAction
// and says so out loud rather than being quietly narrow, so the limit is readable
// instead of being inferable only from what does not go red. Widening it to every
// kind deletes the scope map below and fixes those four tables in the same change;
// until then, a green run here is a claim about FleetAction and nothing else.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"sigs.k8s.io/yaml"
)

// printColumnScope is the kinds this test covers. See SCOPE above: it is a
// declared limit with a named reason, not an omission.
var printColumnScope = map[string]string{
	"FleetAction": "swarmada.io_fleetactions.yaml",
}

// crdPrinterColumns is the sliver of a generated CustomResourceDefinition this
// test reads. A local struct rather than k8s.io/apiextensions-apiserver, which is
// an indirect dependency and would become a direct one for three fields.
type crdPrinterColumns struct {
	Spec struct {
		Names struct {
			Kind string `json:"kind"`
		} `json:"names"`
		Versions []struct {
			Name                     string `json:"name"`
			AdditionalPrinterColumns []struct {
				Name     string `json:"name"`
				JSONPath string `json:"jsonPath"`
				Priority int    `json:"priority"`
			} `json:"additionalPrinterColumns"`
		} `json:"versions"`
	} `json:"spec"`
}

// servedPrintColumns returns the served version's printer columns for one kind,
// split into the default table and the wide-only (priority >= 1) tail — the same
// split resourceDef.column.wide encodes.
func servedPrintColumns(t *testing.T, file, kind string) (normal, wide []string) {
	t.Helper()
	path := filepath.Join("..", "..", "config", "crd", "bases", file)
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	var c crdPrinterColumns
	if err := yaml.Unmarshal(b, &c); err != nil {
		t.Fatalf("parsing %s: %v", path, err)
	}
	if c.Spec.Names.Kind != kind {
		t.Fatalf("%s declares kind %q, expected %q — this test is reading the wrong CRD",
			path, c.Spec.Names.Kind, kind)
	}
	var found bool
	for _, v := range c.Spec.Versions {
		if v.Name != "v1" {
			continue
		}
		found = true
		for _, col := range v.AdditionalPrinterColumns {
			// Age is the creationTimestamp column every kind declares; it is a real
			// column and swarmctl renders it, so it is not special-cased.
			if col.Priority >= 1 {
				wide = append(wide, strings.ToUpper(col.Name))
				continue
			}
			normal = append(normal, strings.ToUpper(col.Name))
		}
	}
	if !found {
		t.Fatalf("%s declares no v1 version", path)
	}
	if len(normal) == 0 {
		t.Fatalf("%s declares no priority-0 printer columns — this test would pass vacuously", path)
	}
	return normal, wide
}

// TestTableMirrorsCRDPrintColumns checks that the registry's columns for each
// in-scope kind are the CRD's printer columns, in the CRD's order, with the same
// default/wide split. Equality, not containment: a column swarmctl invents is as
// much a divergence as one it drops, because `swarmctl get` and `kubectl get`
// claiming to show the same resource must not show different things.
func TestTableMirrorsCRDPrintColumns(t *testing.T) {
	registered := map[string]*resourceDef{}
	for _, r := range resourceOrder {
		registered[r.kind] = r
	}

	for kind, file := range printColumnScope {
		r, ok := registered[kind]
		if !ok {
			t.Fatalf("kind %s is in this test's scope but is not registered — the scope list "+
				"names a kind the CLI does not serve", kind)
		}

		var gotNormal, gotWide []string
		for _, c := range r.columns {
			if c.wide {
				gotWide = append(gotWide, strings.ToUpper(c.header))
				continue
			}
			gotNormal = append(gotNormal, strings.ToUpper(c.header))
		}

		wantNormal, wantWide := servedPrintColumns(t, file, kind)

		if strings.Join(gotNormal, ",") != strings.Join(wantNormal, ",") {
			t.Errorf("%s: `swarmctl get` columns differ from the CRD's printer columns.\n"+
				"  swarmctl: %v\n  CRD:      %v\n"+
				"The CRD is generated from api/v1's +kubebuilder:printcolumn markers and is what "+
				"`kubectl get` shows. A column present in one surface and absent from the other "+
				"means a field the API declares operator-visible is invisible to whichever tool "+
				"the operator happens to use. Fix resources.go, or remove the marker.",
				kind, gotNormal, wantNormal)
		}
		if strings.Join(gotWide, ",") != strings.Join(wantWide, ",") {
			t.Errorf("%s: `swarmctl get -o wide` columns differ from the CRD's priority>=1 "+
				"printer columns.\n  swarmctl: %v\n  CRD:      %v", kind, gotWide, wantWide)
		}
	}
}

// TestFleetActionCarriesTheTwoEvidenceColumns names the two columns by hand, on
// purpose, and is the only hand-written assertion here.
//
// TestTableMirrorsCRDPrintColumns above derives everything, which makes it exactly
// as strong as the CRD it reads: delete a +kubebuilder:printcolumn marker, run
// `make manifests`, delete the matching swarmctl column, and it passes — the two
// surfaces still agree, about a column that is gone. These two are not ordinary
// columns. VERB is the whole operator-surface half of the answer to "what stops
// the verb enum growing one device class at a time", and OUTCOME is the only place
// an operator can tell a Failed the robot reported from a Failed nobody could
// establish. Removing either is a decision, not a refactor, and it should have to
// come here and delete this test to say so.
func TestFleetActionCarriesTheTwoEvidenceColumns(t *testing.T) {
	var def *resourceDef
	for _, r := range resourceOrder {
		if r.kind == "FleetAction" {
			def = r
			break
		}
	}
	if def == nil {
		t.Fatal("FleetAction is not registered")
	}
	headers := map[string]bool{}
	for _, c := range def.columns {
		headers[strings.ToUpper(c.header)] = true
	}
	for _, want := range []struct{ col, why string }{
		{"VERB", "spec.customType — without it every Custom action is an identical opaque row, " +
			"which is the condition that made a Clean look like any other Custom"},
		{"OUTCOME", "status.outcomeCertainty — without it an outcome nobody could establish is " +
			"indistinguishable from an observed failure, and both read as Failed"},
	} {
		if !headers[want.col] {
			t.Errorf("`swarmctl get fleetaction` has no %s column: %s", want.col, want.why)
		}
	}
}
