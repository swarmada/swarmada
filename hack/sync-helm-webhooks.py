# ─────────────────────────────────────────────────────────────────────────────
# Regenerates deploy/swarmada/templates/webhook.yaml from config/webhook/manifests.yaml
# (the controller-gen output). Wired as `make helm-sync-webhooks`; the drift guard is
# `make helm-verify-sync`.
#
# WHY THIS EXISTS. The chart's webhook template was hand-maintained, with only a comment
# ("Mirrors config/webhook/manifests.yaml") holding the two in sync and no gate behind it.
# It drifted: the chart declared 4 of 9 webhooks, so a Helm-installed cluster silently did
# not enforce five validators — including the FleetAction cancel-verb SAR and the rollout
# delete guards. That is the failure mode an ungated hand-mirror produces, and it is why
# the CRDs already had hack/sync-helm-crds.sh. This is the webhook twin of it.
#
# FAILURE POLICY. The chart exposes .Values.webhooks.failurePolicy so an operator can
# loosen admission during a break-glass. That knob is applied ONLY to webhooks whose
# generated policy is Fail. A webhook generated as Ignore is emitted as a literal Ignore,
# because there Ignore is the property, not a tuning default: the ADR-0046 estop-actor
# stampers (attribution must never block a safe stop), and the Robot and SwarmadaConfig
# delete checks vrobotdelete.swarmada.io and vswarmadaconfigdelete.swarmada.io (a manager
# outage must not block a Robot delete or a namespace delete; a namespace delete still waits
# while it holds a FleetZone, FleetTask, FirmwareRollout or ModelRollout, whose DELETE checks
# stay Fail). Letting the chart value tighten them to Fail would invert that.
# ─────────────────────────────────────────────────────────────────────────────
import os
import sys

import yaml

SRC = "config/webhook/manifests.yaml"
OUT = os.environ.get("OUT", "deploy/swarmada/templates/webhook.yaml")

HEADER = """# GENERATED by hack/sync-helm-webhooks.py from config/webhook/manifests.yaml \
— DO NOT EDIT.
# Re-run `make helm-sync` after `make manifests` whenever a +kubebuilder:webhook marker changes.
# SPDX-License-Identifier: Apache-2.0
# Copyright 2026 The Swarmada Authors <maintainers@swarmada.io>
{FOLLOWS}
{{- if .Values.webhooks.enabled -}}
{{- $svc := printf "%s-webhook-service" (include "swarmada.fullname" .) -}}
{{- $certName := printf "%s-serving-cert" (include "swarmada.fullname" .) -}}
# ─────────────────────────────────────────────────────────────────────────────
# Admission webhook Service + configurations.
#
# CA bundle:
#   - cert-manager enabled  → the ca-injector fills clientConfig.caBundle via the
#     cert-manager.io/inject-ca-from annotation (see templates/certificate.yaml).
#   - cert-manager disabled → webhooks.caBundle is written into each clientConfig,
#     and you must create the Secret {{ include "swarmada.webhookCertSecret" . }}.
#
# failurePolicy: webhooks generated as Fail render {{ .Values.webhooks.failurePolicy }}
# so an operator can loosen them; webhooks generated as Ignore render a literal Ignore,
# because there Ignore is the property: the ADR-0046 estop-actor stampers (attribution must
# never block a safe stop), and the Robot and SwarmadaConfig delete checks
# vrobotdelete.swarmada.io and vswarmadaconfigdelete.swarmada.io (a manager outage must not
# block a Robot delete or a namespace delete; a namespace delete still waits while it holds a
# FleetZone, FleetTask, FirmwareRollout or ModelRollout, whose DELETE checks stay Fail).
# Each mutating webhook states its reason beside its policy. A mutating webhook failing
# open stores the object without what it would have written; it does not skip a validation.
# ─────────────────────────────────────────────────────────────────────────────
apiVersion: v1
kind: Service
metadata:
  name: {{ $svc }}
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "swarmada.labels" . | nindent 4 }}
spec:
  selector:
    {{- include "swarmada.selectorLabels" . | nindent 4 }}
  ports:
    - name: webhook
      port: 443
      targetPort: webhook-server
      protocol: TCP
"""

CONFIG_HEAD = """---
apiVersion: admissionregistration.k8s.io/v1
kind: {kind}
metadata:
  name: {{{{ include "swarmada.fullname" . }}}}-{slug}
  labels:
    {{{{- include "swarmada.labels" . | nindent 4 }}}}
  {{{{- if .Values.webhooks.certManager.enabled }}}}
  annotations:
    cert-manager.io/inject-ca-from: {{{{ .Release.Namespace }}}}/{{{{ $certName }}}}
  {{{{- end }}}}
webhooks:
"""


# The webhooks whose failurePolicy follows .Values.webhooks.failurePolicy, as a named template
# defined at the top level (a define may not sit inside the `if`). templates/validate.yaml
# includes it in its refusal of Ignore, so that refusal names every webhook Ignore opens and a
# webhook added here is named there without anyone editing the message.
FOLLOWS = """
{{{{- define "swarmada.webhooksFollowingFailurePolicy" -}}}}
{names}
{{{{- end }}}}
"""


# WHY EACH MUTATING WEBHOOK HAS THE failurePolicy IT HAS. A mutating webhook that fails
# open stores the object WITHOUT WHAT THE WEBHOOK WOULD HAVE WRITTEN — it does not skip a
# validation. So the policy follows what is lost, and the reason is rendered into the
# template beside the policy. A mutating webhook with no entry here fails `make helm-sync`:
# an unexplained Fail/Ignore split is read as intentional whether or not it is.
_STAMPER = (
    "Ignore (ADR-0046): writes no defaults, only the swarmada.io/estop-actor stamp. "
    "Skipped, the estop or resume still lands and is recorded without a verified actor; "
    "blocking a stop on attribution would invert the safety property."
)
MUTATING_REASONS = {
    "mfirmwarerollout.swarmada.io": _STAMPER,
    "mfleetzone.swarmada.io": _STAMPER,
    "mmodelrollout.swarmada.io": _STAMPER,
    "mswarmadaconfig.swarmada.io": _STAMPER,
    "mrobot.swarmada.io": (
        "Fail: runs the RobotClass merge (identity, adapter, per-field constraints and "
        "charging limits, telemetry cadence). The merge runs only on create or a "
        "spec.robotClass change, so a skipped merge is never retried and the Robot is "
        "stored without its class's safety limits."
    ),
}


def render_webhook(w, mutating=False):
    """One webhook entry, with the chart's service/caBundle indirection restored."""
    policy = w.get("failurePolicy", "Fail")
    if policy == "Fail":
        policy_line = "{{ .Values.webhooks.failurePolicy }}"
    else:
        policy_line = policy
    out = [
        "  - admissionReviewVersions:",
        "      - v1",
        "    clientConfig:",
        "      service:",
        "        name: {{ $svc }}",
        "        namespace: {{ .Release.Namespace }}",
        f"        path: {w['clientConfig']['service']['path']}",
        "      {{- if and (not .Values.webhooks.certManager.enabled) .Values.webhooks.caBundle }}",
        "      caBundle: {{ .Values.webhooks.caBundle }}",
        "      {{- end }}",
    ]
    if mutating:
        reason = MUTATING_REASONS.get(w["name"])
        if reason is None:
            raise SystemExit(
                f"{w['name']}: a mutating webhook with no stated failurePolicy reason; "
                "add it to MUTATING_REASONS in hack/sync-helm-webhooks.py"
            )
        words, line = reason.split(), "    #"
        for word in words:
            if len(line) + 1 + len(word) > 96:
                out.append(line)
                line = "    #"
            line += " " + word
        out.append(line)
    out += [
        f"    failurePolicy: {policy_line}",
        f"    name: {w['name']}",
        "    rules:",
    ]
    for r in w.get("rules", []):
        groups = ", ".join(f'"{g}"' for g in r.get("apiGroups", []))
        versions = ", ".join(f'"{v}"' for v in r.get("apiVersions", []))
        ops = ", ".join(f'"{o}"' for o in r.get("operations", []))
        resources = ", ".join(f'"{x}"' for x in r.get("resources", []))
        out += [
            f"      - apiGroups: [{groups}]",
            f"        apiVersions: [{versions}]",
            f"        operations: [{ops}]",
            f"        resources: [{resources}]",
        ]
    out.append(f"    sideEffects: {w.get('sideEffects', 'None')}")
    return "\n".join(out) + "\n"


def main():
    if not os.path.exists(SRC):
        print(f"{SRC} not found; run `make manifests` first", file=sys.stderr)
        return 1
    docs = [d for d in yaml.safe_load_all(open(SRC)) if d]
    by_kind = {d["kind"]: d for d in docs}

    parts = [HEADER]
    total = 0
    follows = []
    for kind, slug in (
        ("MutatingWebhookConfiguration", "mutating-webhook-configuration"),
        ("ValidatingWebhookConfiguration", "validating-webhook-configuration"),
    ):
        cfg = by_kind.get(kind)
        if not cfg or not cfg.get("webhooks"):
            continue
        parts.append(CONFIG_HEAD.format(kind=kind, slug=slug))
        # Sorted by name so the generated file is stable across controller-gen runs.
        for w in sorted(cfg["webhooks"], key=lambda x: x["name"]):
            parts.append(render_webhook(w, mutating=kind == "MutatingWebhookConfiguration"))
            total += 1
            if w.get("failurePolicy", "Fail") == "Fail":
                follows.append(w["name"])
    parts.append("{{- end }}\n")
    parts[0] = HEADER.replace("{FOLLOWS}", FOLLOWS.format(names=", ".join(sorted(follows))))

    with open(OUT, "w") as f:
        f.write("".join(parts))
    print(f"wrote {OUT} ({total} webhooks from {SRC})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
